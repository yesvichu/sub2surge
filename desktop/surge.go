package main

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const (
	// surgeCLIEnv overrides where surge-cli is looked up.
	surgeCLIEnv = "SURGE_CLI"
	// surgeManagedMarker appears in the header of every profile this app
	// writes, so overwriting a hand-written profile needs a confirmation.
	surgeManagedMarker = "generated by sub2surge"
	// surgeBackupKeep is how many backups of a profile are kept.
	surgeBackupKeep = 10

	surgeCheckTimeout  = 60 * time.Second
	surgeReloadTimeout = 120 * time.Second
)

// surgeSetup is where Surge keeps its files and how to reach its CLI.
type surgeSetup struct {
	cli        string
	profileDir string
	backupDir  string
}

// SurgeStatus is what the page shows about the local Surge install.
type SurgeStatus struct {
	Installed   bool   `json:"installed"`
	CLI         string `json:"cli"`
	CurrentName string `json:"current_name"`
	CurrentPath string `json:"current_path"`
	Managed     bool   `json:"managed"`
	Problem     string `json:"problem,omitempty"`
}

// ApplySurgeRequest carries the profile to write over Surge's active one.
type ApplySurgeRequest struct {
	Config string `json:"config"`
	// Force overwrites a profile this app did not generate.
	Force bool `json:"force"`
}

// ApplySurgeResponse reports what was written and how Surge took it.
type ApplySurgeResponse struct {
	ProfileName  string `json:"profile_name"`
	ProfilePath  string `json:"profile_path"`
	BackupPath   string `json:"backup_path"`
	ReloadOutput string `json:"reload_output"`
}

// detectSurge locates the CLI and Surge's profile directory.
func detectSurge() (*surgeSetup, error) {
	cli, err := surgeCLIPath()
	if err != nil {
		return nil, err
	}
	configDir, err := os.UserConfigDir()
	if err != nil {
		return nil, fmt.Errorf("找不到用户配置目录：%w", err)
	}
	return &surgeSetup{
		cli:        cli,
		profileDir: filepath.Join(configDir, "Surge", "Profiles"),
		backupDir:  filepath.Join(configDir, "Sub2Surge", "surge-backups"),
	}, nil
}

// surgeCLIPath finds surge-cli: an explicit SURGE_CLI, then the app bundle,
// then whatever PATH offers.
func surgeCLIPath() (string, error) {
	if override := strings.TrimSpace(os.Getenv(surgeCLIEnv)); override != "" {
		if isExecutableFile(override) {
			return override, nil
		}
		return "", fmt.Errorf("%s 指向的 %q 不可执行", surgeCLIEnv, override)
	}

	candidates := []string{"/Applications/Surge.app/Contents/Applications/surge-cli"}
	if home, err := os.UserHomeDir(); err == nil {
		candidates = append(candidates,
			filepath.Join(home, "Applications", "Surge.app", "Contents", "Applications", "surge-cli"))
	}
	for _, candidate := range candidates {
		if isExecutableFile(candidate) {
			return candidate, nil
		}
	}
	if found, err := exec.LookPath("surge-cli"); err == nil {
		return found, nil
	}
	return "", errors.New("没有找到 surge-cli，请确认已安装 Surge for macOS")
}

func isExecutableFile(path string) bool {
	info, err := os.Stat(path)
	if err != nil || info.IsDir() {
		return false
	}
	return info.Mode()&0o111 != 0
}

// runSurgeCLI runs one surge-cli command and returns its combined output.
func runSurgeCLI(ctx context.Context, cli string, timeout time.Duration, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()

	command := exec.CommandContext(ctx, cli, args...)
	var out bytes.Buffer
	command.Stdout = &out
	command.Stderr = &out
	// Never leave the app waiting on a CLI that will not exit.
	command.WaitDelay = 5 * time.Second

	runErr := command.Run()
	output := strings.TrimSpace(out.String())
	if runErr == nil {
		return output, nil
	}
	if ctx.Err() != nil {
		return output, fmt.Errorf("surge-cli %s 超时", strings.Join(args, " "))
	}
	if output == "" {
		return output, fmt.Errorf("surge-cli %s 失败：%w", strings.Join(args, " "), runErr)
	}
	return output, fmt.Errorf("surge-cli %s 失败：%s", strings.Join(args, " "), output)
}

// parseCurrentProfile reads "Current Profile: <name>" from the CLI output.
func parseCurrentProfile(output string) (string, error) {
	for line := range strings.SplitSeq(output, "\n") {
		rest, ok := strings.CutPrefix(strings.TrimSpace(line), "Current Profile:")
		if !ok {
			continue
		}
		name := strings.TrimSpace(rest)
		if name == "" {
			return "", errors.New("没有启用中的 Surge 配置")
		}
		return name, nil
	}
	return "", fmt.Errorf("无法解析 surge-cli profile current 的输出：%q", output)
}

// isSub2SurgeProfile reports whether the profile came from this app.
func isSub2SurgeProfile(data []byte) bool {
	head := data
	if len(head) > 2048 {
		head = head[:2048]
	}
	return strings.Contains(strings.ToLower(string(head)), surgeManagedMarker)
}

// surge returns the setup, detecting it once.
func (c *Converter) surge() (*surgeSetup, error) {
	c.surgeMu.Lock()
	defer c.surgeMu.Unlock()
	if c.surgeInstall != nil {
		return c.surgeInstall, nil
	}
	setup, err := detectSurge()
	if err != nil {
		return nil, err
	}
	c.surgeInstall = setup
	return setup, nil
}

// SurgeStatus reports whether the page can offer to write into Surge. Problems
// come back in the struct so the page renders a reason instead of an error.
func (c *Converter) SurgeStatus(ctx context.Context) SurgeStatus {
	setup, err := c.surge()
	if err != nil {
		return SurgeStatus{Problem: err.Error()}
	}
	status := SurgeStatus{Installed: true, CLI: setup.cli}

	name, err := c.currentSurgeProfile(ctx, setup)
	if err != nil {
		status.Problem = err.Error()
		return status
	}
	status.CurrentName = name
	status.CurrentPath = filepath.Join(setup.profileDir, name+".conf")

	if existing, readErr := os.ReadFile(status.CurrentPath); readErr == nil {
		status.Managed = isSub2SurgeProfile(existing)
	}
	return status
}

// ApplyToSurge writes the profile over Surge's active one, keeps a backup of
// what was there, and asks Surge to reload.
func (c *Converter) ApplyToSurge(ctx context.Context, req ApplySurgeRequest) (ApplySurgeResponse, error) {
	if strings.TrimSpace(req.Config) == "" {
		return ApplySurgeResponse{}, errors.New("没有可写入的内容，请先转换")
	}
	ctx, cancel := context.WithTimeout(ctx, 3*time.Minute)
	defer cancel()

	setup, err := c.surge()
	if err != nil {
		return ApplySurgeResponse{}, err
	}
	name, err := c.currentSurgeProfile(ctx, setup)
	if err != nil {
		return ApplySurgeResponse{}, err
	}
	target := filepath.Join(setup.profileDir, name+".conf")

	existing, readErr := os.ReadFile(target)
	switch {
	case readErr == nil && !req.Force && !isSub2SurgeProfile(existing):
		return ApplySurgeResponse{}, fmt.Errorf(
			"当前配置「%s」不是 Sub2Surge 生成的，为避免覆盖手写配置已中止；确认覆盖请重试并选择强制", name)
	case readErr != nil && !errors.Is(readErr, os.ErrNotExist):
		return ApplySurgeResponse{}, fmt.Errorf("读取当前配置失败：%w", readErr)
	}

	// Validate before touching the live profile: a rejected profile would
	// otherwise leave Surge without a working configuration.
	staged, cleanup, err := stageProfile(req.Config)
	if err != nil {
		return ApplySurgeResponse{}, err
	}
	defer cleanup()
	if _, err := runSurgeCLI(ctx, setup.cli, surgeCheckTimeout, "--check", staged); err != nil {
		return ApplySurgeResponse{}, fmt.Errorf("这份配置被 Surge 拒绝：%w", err)
	}

	resp := ApplySurgeResponse{ProfileName: name, ProfilePath: target}
	if readErr == nil {
		backup, err := backupSurgeProfile(setup, name, existing)
		if err != nil {
			return ApplySurgeResponse{}, err
		}
		resp.BackupPath = backup
	}

	if err := os.WriteFile(target, []byte(req.Config), 0o644); err != nil {
		return ApplySurgeResponse{}, fmt.Errorf("写入配置失败：%w", err)
	}

	output, err := runSurgeCLI(ctx, setup.cli, surgeReloadTimeout, "reload")
	resp.ReloadOutput = output
	if err != nil {
		return resp, fmt.Errorf("配置已写入，但 Surge 重载失败：%w", err)
	}
	return resp, nil
}

// currentSurgeProfile asks Surge which profile is active.
func (c *Converter) currentSurgeProfile(ctx context.Context, setup *surgeSetup) (string, error) {
	output, err := runSurgeCLI(ctx, setup.cli, surgeCheckTimeout, "profile", "current")
	if err != nil {
		return "", err
	}
	return parseCurrentProfile(output)
}

// stageProfile writes content to a temporary file for surge-cli --check, which
// accepts any path. The returned cleanup removes it.
func stageProfile(content string) (string, func(), error) {
	file, err := os.CreateTemp("", "sub2surge-check-*.conf")
	if err != nil {
		return "", func() {}, fmt.Errorf("创建临时配置失败：%w", err)
	}
	name := file.Name()
	cleanup := func() { _ = os.Remove(name) }
	if _, err := file.WriteString(content); err != nil {
		_ = file.Close()
		cleanup()
		return "", func() {}, fmt.Errorf("写入临时配置失败：%w", err)
	}
	if err := file.Close(); err != nil {
		cleanup()
		return "", func() {}, fmt.Errorf("关闭临时配置失败：%w", err)
	}
	return name, cleanup, nil
}

// backupSurgeProfile copies the current profile aside and prunes old copies.
func backupSurgeProfile(setup *surgeSetup, name string, content []byte) (string, error) {
	if err := os.MkdirAll(setup.backupDir, 0o700); err != nil {
		return "", fmt.Errorf("创建备份目录失败：%w", err)
	}
	stamp := time.Now().Format("20060102-150405")
	backup := filepath.Join(setup.backupDir, fmt.Sprintf("%s-%s.conf", name, stamp))
	if err := os.WriteFile(backup, content, 0o600); err != nil {
		return "", fmt.Errorf("备份当前配置失败：%w", err)
	}
	pruneSurgeBackups(setup.backupDir, name)
	return backup, nil
}

// pruneSurgeBackups keeps only the newest surgeBackupKeep backups of a name.
func pruneSurgeBackups(dir, name string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return
	}
	var mine []string
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasPrefix(entry.Name(), name+"-") {
			continue
		}
		mine = append(mine, entry.Name())
	}
	if len(mine) <= surgeBackupKeep {
		return
	}
	// The timestamp sorts lexicographically, so the oldest come first.
	sort.Strings(mine)
	for _, old := range mine[:len(mine)-surgeBackupKeep] {
		_ = os.Remove(filepath.Join(dir, old))
	}
}
