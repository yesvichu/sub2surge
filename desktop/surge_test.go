// fakeSurge writes a stand-in surge-cli that answers like the real one: it
// prints "Current Profile:" for profile current, accepts --check, and records
// every reload it was asked to do.
func fakeSurge(t *testing.T, dir, profileName string) (cli string, logPath string) {
	t.Helper()

	logPath = filepath.Join(dir, "cli.log")
	script := `#!/bin/sh
printf '%s\n' "$*" >> '` + logPath + `'
case "$1" in
  profile)
    echo "Current Profile: ` + profileName + `"
    ;;
  --check)
    if grep -q notaprotocol "$2"; then
      echo "Failed: 第 2 行存在无效配置"
      exit 1
    fi
    echo "OK"
    ;;
  reload)
    echo "success"
    ;;
  *)
    echo "unexpected: $*" >&2
    exit 2
    ;;
esac
`
	cli = filepath.Join(dir, "surge-cli")
	if err := os.WriteFile(cli, []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	return cli, logPath
}

func newSurgeConverter(t *testing.T, profileName string) (*Converter, *surgeSetup, string) {
	t.Helper()

	dir := t.TempDir()
	cli, logPath := fakeSurge(t, dir, profileName)
	setup := &surgeSetup{
		cli:        cli,
		profileDir: filepath.Join(dir, "Profiles"),
		backupDir:  filepath.Join(dir, "backups"),
	}
	if err := os.MkdirAll(setup.profileDir, 0o755); err != nil {
		t.Fatal(err)
	}

	c := newConverter(t.TempDir())
	c.surgeInstall = setup
	return c, setup, logPath
}

const generatedProfile = `# Sub2Surge export
# Generated by sub2surge 0.2.0 at 2026-11-17T00:00:00+08:00

[General]
loglevel = notify

[Proxy]
HK-1 = trojan, a.example.com, 443, password=pw

[Rule]
FINAL,DIRECT
`

func TestSurgeStatusReportsManagedProfile(t *testing.T) {
	c, setup, _ := newSurgeConverter(t, "🍟")
	target := filepath.Join(setup.profileDir, "🍟.conf")
	if err := os.WriteFile(target, []byte(generatedProfile), 0o644); err != nil {
		t.Fatal(err)
	}

	status := c.SurgeStatus(t.Context())
	if !status.Installed || status.Problem != "" {
		t.Fatalf("status = %+v", status)
	}
	if status.CurrentName != "🍟" || status.CurrentPath != target {
		t.Errorf("current = %q at %q, want 🍟 at %q", status.CurrentName, status.CurrentPath, target)
	}
	if !status.Managed {
		t.Error("a profile this app generated should report as managed")
	}
}

