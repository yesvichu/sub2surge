// Package surgefile renders Surge profile files. It is shared by the HTTP
// endpoint, the CLI's -out mode and the MyGo desktop app, so all three produce
// the same importable file.
package surgefile

import (
	"fmt"
	"strings"
	"time"

	"github.com/yesvichu/sub2surge/internal/model"
	"github.com/yesvichu/sub2surge/internal/version"
)

// ProfileOptions configures a Surge configuration file.
type ProfileOptions struct {
	// ManagedConfigURL adds a "#!MANAGED-CONFIG" header, turning the file into
	// a managed profile that Surge refreshes from this URL. Leave empty for a
	// normal file the user imports once.
	ManagedConfigURL string
	Title            string
	GeneratedAt      time.Time
	// Rules is the body of the [Rule] section. Empty means FINAL,DIRECT only;
	// DefaultRules provides the built-in template.
	Rules string
	// ExtraGroups adds the selected policy groups; there are no built-in ones.
	// DefaultProxyGroups adapts the Surge profile's groups to the new nodes.
	ExtraGroups []string
}

// RenderProfile returns a complete, importable Surge profile:
//
//	[General]
//	[Proxy]
//	[Proxy Group]
//	[Rule]
func RenderProfile(lines []string, opts ProfileOptions) string {
	generated := opts.GeneratedAt
	if generated.IsZero() {
		generated = time.Now()
	}

	var b strings.Builder
	if opts.ManagedConfigURL != "" {
		fmt.Fprintf(&b, "#!MANAGED-CONFIG %s interval=86400 strict=false\n", opts.ManagedConfigURL)
	}
	if opts.Title != "" {
		fmt.Fprintf(&b, "# %s\n", opts.Title)
	}
	fmt.Fprintf(&b, "# Generated by sub2surge %s at %s\n", version.Version, generated.Format(time.RFC3339))
	b.WriteString("# 在 Surge 中导入：配置 → + → 从文件导入。\n")

	b.WriteString("\n[General]\nloglevel = notify\n")
	b.WriteString("\n[Proxy]\n")
	for _, line := range lines {
		b.WriteString(line)
		b.WriteByte('\n')
	}

	if len(opts.ExtraGroups) > 0 {
		b.WriteString("\n[Proxy Group]\n")
		for _, group := range opts.ExtraGroups {
			b.WriteString(group)
			b.WriteByte('\n')
		}
	}

	b.WriteString("\n[Rule]\n")
	if rules := strings.TrimSpace(opts.Rules); rules != "" {
		b.WriteString(strings.TrimRight(opts.Rules, "\n"))
		b.WriteByte('\n')
	} else {
		b.WriteString("FINAL,DIRECT\n")
	}
	return b.String()
}

// ProxyLines returns just the "[Proxy]" section's lines. This is the format
// Surge accepts for policy-path and the easiest thing to paste into an
// existing profile.
func ProxyLines(lines []string) string {
	if len(lines) == 0 {
		return ""
	}
	return strings.Join(lines, "\n") + "\n"
}

// RenderList returns proxy lines with human-readable comments. Surge ignores
// "#" comment lines in a policy-path list.
func RenderList(lines []string, skips []model.Skip, header []string) string {
	var b strings.Builder
	for _, line := range header {
		if !strings.HasPrefix(line, "#") {
			line = "# " + line
		}
		b.WriteString(line)
		b.WriteByte('\n')
	}
	fmt.Fprintf(&b, "# sub2surge %s | %d proxies | %d skipped | %s\n",
		version.Version, len(lines), len(skips), time.Now().Format(time.RFC3339))
	for _, line := range SummarizeSkips(skips, 6) {
		fmt.Fprintf(&b, "# skipped: %s\n", line)
	}
	for _, line := range lines {
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return b.String()
}

// SummarizeSkips groups skip reasons so a subscription with 200 unsupported
// nodes produces a handful of comments rather than 200.
func SummarizeSkips(skips []model.Skip, limit int) []string {
	if len(skips) == 0 {
		return nil
	}
	type bucket struct {
		count  int
		reason string
	}
	order := make([]string, 0, len(skips))
	buckets := make(map[string]*bucket, len(skips))
	for _, skip := range skips {
		scheme := skip.Scheme
		if scheme == "" {
			scheme = "unknown"
		}
		key := scheme + "\x00" + skip.Reason
		item := buckets[key]
		if item == nil {
			item = &bucket{reason: skip.Reason}
			buckets[key] = item
			order = append(order, key)
		}
		item.count++
	}

	result := make([]string, 0, len(order))
	for _, key := range order {
		item := buckets[key]
		scheme, _, _ := strings.Cut(key, "\x00")
		result = append(result, fmt.Sprintf("%s x%d (%s)", scheme, item.count, item.reason))
		if limit > 0 && len(result) == limit {
			if remaining := len(order) - len(result); remaining > 0 {
				result = append(result, fmt.Sprintf("... and %d more kind(s)", remaining))
			}
			break
		}
	}
	return result
}
